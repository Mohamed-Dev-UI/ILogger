/**
 * KSP entry point. Options:
 *
 * - `ilogger.enabled` (default `true`) — master switch; `false` disables all
 *   generation so builds can compile-time disable instrumentation.
 * - `ilogger.verbose` (default `false`) — logs every generated file path.
 * - `ilogger.expect-diagnostics` (default `false`) — fixture mode for the
 *   diagnostics test-suite: invalid `@Log` usages become *warnings* instead
 *   of fatal KSP errors, and all diagnostics are collected into a
 *   `ilogger-diagnostics.txt` report next to the generated sources for the
 *   `ksp-diagnostics` module's assertions.
 * - `ilogger.domain-packages` (default empty) — comma-separated package
 *   prefixes eligible for entity inference. When set, only types under these
 *   prefixes are inferred as entities; when empty, the default blacklist
 *   (framework, stdlib, primitive and logger-internal packages) applies.
 * - `ilogger.suppress` (default empty) — comma-separated diagnostic codes
 *   (`ILG019`, ...) suppressed for the whole module. Per-symbol
 *   `@Suppress("ILGxxx")` works without this option.
 * - `ilogger.require-actor` (default `false`) — warns when an AUDIT operation
 *   has no explicit `@Log(actor = ...)` and therefore depends on the ambient
 *   actor/actorProvider.
 * - `ilogger.sink-categories` (default empty) — comma-separated categories
 *   that have a sink binding. When non-empty, @Log categories outside the set
 *   warn (ILG021).
 * - `ilogger.schema-output` (default empty) — extra filesystem path for the
 *   action schema manifest (also emitted as
 *   `META-INF/ilogger/schema.json` in the generated resources). Pass an
 *   absolute path from Gradle for CI diffing.
 */
public class ILoggerProcessorProvider : SymbolProcessorProvider {
    override fun create(environment: SymbolProcessorEnvironment): SymbolProcessor =
        ILoggerProcessor(environment)
}

/**
 * Multi-round processor: each KSP round sees the files generated by the
 * previous one, so `@Log` interfaces produced by other processors are
 * instrumented in a later round. Unresolved symbols are returned to KSP and
 * revisited instead of failing eagerly.
 *
 * Incremental correctness: interface wrappers declare isolating dependencies
 * on the interface file plus every source file whose declarations appear in
 * the generated code; database facades stay aggregating because duplicate
 * binding detection spans all databases in the compilation.
 */
internal class ILoggerProcessor(
    private val environment: SymbolProcessorEnvironment,
) : SymbolProcessor {

    private val processedInterfaces = HashSet<String>()
    private val deferredInterfaces = HashSet<String>()
    private val processedClasses = HashSet<String>()
    private val processedTopLevel = HashSet<String>()
    private val processedDatabases = HashSet<String>()
    private val processedActionObjects = HashSet<String>()
    private val wrappedDaos = HashSet<String>()
    private val hiltOwners = HashMap<String, String>()
    private val koinOwners = HashMap<String, String>()
    private val enabledDaoDeclarations = LinkedHashMap<String, KSClassDeclaration>()
    private val exposedDaoFqns = LinkedHashSet<String>()
    private val warnedUnusedDaos = HashSet<String>()
    private val emittedDiagnostics = HashSet<String>()
    private val diagnosticLines = LinkedHashSet<String>()
    private var diagnosticsWritten = false

    /** Action contracts accumulated across rounds, keyed by (action, schemaVersion). */
    private val actionSchemas = LinkedHashMap<Pair<String, Int>, ActionSchema>()
    private val declaredActions = LinkedHashSet<String>()
    private val declaredActionSources = HashMap<String, String>()
    private val warnedDuplicateDeclarations = HashSet<String>()
    private val warnedDuplicateEmissions = HashSet<String>()
    private val warnedUndeclaredActions = HashSet<String>()
    private var schemaManifestWritten = false

    override fun finish() {
        writeSchemaManifest()
    }

    override fun process(resolver: Resolver): List<KSAnnotated> {
        val enabled = environment.options["ilogger.enabled"] ?: "true"
        if (enabled.equals("false", ignoreCase = true)) return emptyList()
        val verbose = environment.options["ilogger.verbose"]?.equals("true", ignoreCase = true) ?: false
        val strict = environment.options["ilogger.strict"]?.equals("true", ignoreCase = true) ?: false
        val expectDiagnostics =
            environment.options["ilogger.expect-diagnostics"]?.equals("true", ignoreCase = true) ?: false
        val requireActor = environment.options["ilogger.require-actor"]?.equals("true", ignoreCase = true) ?: false
        val suppressedCodes = environment.options["ilogger.suppress"]
            ?.split(',')
            ?.map { it.trim().uppercase() }
            ?.filter { it.isNotEmpty() }
            ?.toSet()
            ?: emptySet()
        val sinkCategories = environment.options["ilogger.sink-categories"]
            ?.split(',')
            ?.map { it.trim() }
            ?.filter { it.isNotEmpty() }
            ?.toSet()
            ?: emptySet()
        val domainPackages = environment.options["ilogger.domain-packages"]
            ?.split(',')
            ?.map { it.trim() }
            ?.filter { it.isNotEmpty() }
            ?.toSet()
            ?: emptySet()
        val autoChangesOption = environment.options["ilogger.auto-changes"]?.trim()?.lowercase()
        val autoChangesDefault = autoChangesOption == "all" || autoChangesOption == "true"

        val deferred = LinkedHashSet<KSAnnotated>()

        fun emit(diagnostic: Diagnostic, message: String, symbol: Any) {
            if (diagnostic.code in suppressedCodes || suppressedAt(symbol, diagnostic.code)) return
            val text = diagnostic.message(message)
            val label = fileLabelOf(symbol)
            val key = if (label != null) "$label :: $text" else text
            if (!emittedDiagnostics.add(key)) return
            if (label != null) diagnosticLines += "$label :: $text"
            val fatal = !diagnostic.isWarning && !expectDiagnostics ||
                diagnostic.isWarning && strict && !expectDiagnostics
            environment.logger.run {
                if (fatal) error(text, nodeOf(symbol)) else warn(text, nodeOf(symbol))
            }
        }

        val parser = OpParser(
            report = ::emit,
            domainPackages = domainPackages,
            requireActor = requireActor,
            sinkCategories = sinkCategories,
            autoChangesDefault = autoChangesDefault,
        )

        // Registries first: the same round's @Log usages are checked against them.
        processActionRegistries(resolver, ::emit)

        val annotated = resolver.getSymbolsWithAnnotation(Ks.LOG_FQN).toList()
        val logDaoSymbols = resolver.getSymbolsWithAnnotation(Ks.LOG_DAO_FQN).toList()

        // ---- @Log: wrappers (one generated file per interface/class/function) --
        val groups = LinkedHashMap<String, MutableList<KSFunctionDeclaration>>()
        val classGroups = LinkedHashMap<String, MutableList<KSFunctionDeclaration>>()
        val topLevelGroups = LinkedHashMap<String, MutableList<KSFunctionDeclaration>>()
        for (symbol in annotated) {
            val fn = symbol as? KSFunctionDeclaration
            if (fn == null) {
                if (symbol !is KSDeclaration || symbol.containingFile != null) {
                    emit(
                        Diagnostic.LOG_TARGET,
                        "@Log can only annotate functions.\n" +
                            "Fix: apply @Log to a function of an interface (DAO/repository/use-case).",
                        symbol,
                    )
                }
                continue
            }
            // @NoLog wins over @Log: the member is excluded from every wrapper.
            if (Ks.annotation(fn, Ks.NO_LOG_FQN) != null) continue
            val parent = fn.parentDeclaration as? KSClassDeclaration
            if (parent == null) {
                // Top-level function (plain or extension): grouped per package
                // and name so overloads share one generated file.
                if (fn.containingFile == null) continue
                if (fn.packageName.asString().isBlank()) {
                    // Parse only to surface the default-package diagnostic.
                    val annotation = Ks.annotation(fn, Ks.LOG_FQN) ?: continue
                    parser.parse(fn, annotation, roomKindOf(fn), Container.TopLevel)
                    continue
                }
                val key = "${fn.packageName.asString()}::${fn.simpleName.asString()}"
                topLevelGroups.getOrPut(key) { ArrayList() } += fn
                continue
            }
            when (parent.classKind) {
                ClassKind.INTERFACE -> {
                    if (parent.containingFile == null) continue // compiled in another module
                    val fqn = parent.qualifiedName?.asString() ?: continue
                    if (fqn in processedInterfaces) continue
                    groups.getOrPut(fqn) { ArrayList() } += fn
                }
                ClassKind.CLASS -> {
                    if (parent.containingFile == null) continue // compiled in another module
                    val fqn = parent.qualifiedName?.asString() ?: continue
                    if (Modifier.OPEN in parent.modifiers || Modifier.ABSTRACT in parent.modifiers) {
                        if (fqn in processedClasses) continue
                        classGroups.getOrPut(fqn) { ArrayList() } += fn
                    } else {
                        // Final classes can be neither subclassed nor proxied;
                        // the planned compiler plugin will lift this (G-17b).
                        emit(
                            Diagnostic.FINAL_CLASS,
                            "@Log member '${fn.simpleName.asString()}' is in a final class " +
                                "'${parent.simpleName.asString()}'. ILogger instruments classes by generating a " +
                                "subclass wrapper, which requires the class to be open or abstract, and instances " +
                                "of final classes cannot be proxied.\n" +
                                "Fix: mark the class open or abstract, move the operation into an interface, or " +
                                "instrument the call site with ILogger.record(...).",
                            fn,
                        )
                    }
                }
                else -> {
                    // OpParser reports the actionable diagnostic (once, thanks to dedupe).
                    val annotation = Ks.annotation(fn, Ks.LOG_FQN) ?: continue
                    parser.parse(fn, annotation, roomKindOf(fn), Container.Rejected)
                }
            }
        }

        for ((fqn, functions) in groups) {
            val interfaceDecl = functions.first().parentDeclaration as KSClassDeclaration
            if (functions.any { hasUnresolvedTypes(it) }) {
                // Another processor may still generate the missing type; never
                // emit a partial wrapper for the interface.
                deferred += functions
                deferredInterfaces += fqn
                continue
            }
            deferredInterfaces -= fqn

            val ops = ArrayList<ResolvedOp>(functions.size)
            var invalid = false
            for (fn in functions) {
                val annotation = Ks.annotation(fn, Ks.LOG_FQN) ?: continue
                val op = parser.parse(fn, annotation, roomKindOf(fn), Container.Interface(interfaceDecl))
                if (op == null) {
                    invalid = true
                } else {
                    ops += op
                    recordSchema(op, ::emit)
                }
            }
            processedInterfaces += fqn
            if (invalid || ops.isEmpty()) continue

            val file = Codegen.buildInterfaceFile(interfaceDecl, ops)
            file.writeTo(
                environment.codeGenerator,
                wrapperDependencies(listOfNotNull(interfaceDecl.containingFile), ops),
            )
            wrappedDaos += fqn
            if (verbose) {
                environment.logger.info(
                    "ilogger-ksp: generated ${file.name} for ${ops.size} @Log op(s) " +
                        "(${interfaceDecl.qualifiedName?.asString()}).",
                )
            }
        }

        // ---- @Log on open/abstract classes: subclass wrappers -------------------
        for ((fqn, functions) in classGroups) {
            val classDecl = functions.first().parentDeclaration as KSClassDeclaration
            if (functions.any { hasUnresolvedTypes(it) }) {
                deferred += functions
                continue
            }

            val ctor = classDecl.primaryConstructor
            if (Modifier.INNER in classDecl.modifiers) {
                emit(
                    Diagnostic.CLASS_MEMBER_SHAPE,
                    "@Log members of inner class '${classDecl.simpleName.asString()}' cannot be wrapped: the " +
                        "generated subclass needs an outer instance.\n" +
                        "Fix: make the class non-inner, or move the operations into an interface.",
                    classDecl,
                )
                processedClasses += fqn
                continue
            }
            if (ctor != null && Modifier.PRIVATE in ctor.modifiers) {
                emit(
                    Diagnostic.CLASS_MEMBER_SHAPE,
                    "@Log class '${classDecl.simpleName.asString()}' has a private primary constructor; the " +
                        "generated subclass cannot call it.\n" +
                        "Fix: make the primary constructor internal or protected, or move the operations into " +
                        "an interface.",
                    classDecl,
                )
                processedClasses += fqn
                continue
            }

            val ops = ArrayList<ResolvedOp>(functions.size)
            var invalid = false
            for (fn in functions) {
                val annotation = Ks.annotation(fn, Ks.LOG_FQN) ?: continue
                val op = parser.parse(fn, annotation, roomKindOf(fn), Container.OpenClass(classDecl))
                if (op == null) {
                    invalid = true
                } else {
                    ops += op
                    recordSchema(op, ::emit)
                }
            }
            processedClasses += fqn
            if (invalid || ops.isEmpty()) continue

            val file = Codegen.buildClassFile(classDecl, ops)
            file.writeTo(
                environment.codeGenerator,
                wrapperDependencies(listOfNotNull(classDecl.containingFile), ops),
            )
            if (verbose) {
                environment.logger.info(
                    "ilogger-ksp: generated ${file.name} for ${ops.size} @Log op(s) " +
                        "(${classDecl.qualifiedName?.asString()}).",
                )
            }
        }

        // ---- @Log on top-level functions: adapter wrappers ----------------------
        for ((key, functions) in topLevelGroups) {
            if (functions.any { hasUnresolvedTypes(it) }) {
                deferred += functions
                continue
            }

            val ops = ArrayList<ResolvedOp>(functions.size)
            var invalid = false
            for (fn in functions) {
                val annotation = Ks.annotation(fn, Ks.LOG_FQN) ?: continue
                val op = parser.parse(fn, annotation, roomKindOf(fn), Container.TopLevel)
                if (op == null) {
                    invalid = true
                } else {
                    ops += op
                    recordSchema(op, ::emit)
                }
            }
            processedTopLevel += key
            if (invalid || ops.isEmpty()) continue

            val file = Codegen.buildTopLevelFile(ops)
            val sourceFiles = functions.mapNotNull { it.containingFile }
            file.writeTo(environment.codeGenerator, wrapperDependencies(sourceFiles, ops))
            if (verbose) {
                environment.logger.info(
                    "ilogger-ksp: generated ${file.name} for ${ops.size} @Log op(s) (${key}).",
                )
            }
        }

        // ---- @LogDao: database facades and DI bindings -------------------------
        // @LogDao only selects which DAOs the generated database facade wraps;
        // it never synthesizes actions. Methods still need an explicit @Log.
        val enabledDaos = LinkedHashSet<String>()
        val hiltDaos = LinkedHashSet<String>()
        val koinDaos = LinkedHashSet<String>()
        val hiltAvailable = hasHilt(resolver)
        val koinAvailable = hasKoin(resolver)
        for (symbol in logDaoSymbols) {
            val declaration = symbol as? KSClassDeclaration
            if (declaration == null || declaration.classKind != ClassKind.INTERFACE) {
                emit(
                    Diagnostic.LOG_DAO_TARGET,
                    "@LogDao can only annotate an interface.\n" +
                        "Fix: apply it to the DAO interface (Room's @Dao types are interfaces).",
                    symbol,
                )
                continue
            }
            // Annotations from dependency modules are compile-time input only:
            // never generate a facade into another module's package.
            if (declaration.containingFile == null) continue
            val fqn = declaration.qualifiedName?.asString() ?: continue
            val options = logDaoOptions(declaration)
            if (options.enabled) {
                enabledDaos += fqn
                enabledDaoDeclarations.putIfAbsent(fqn, declaration)
            }
            if (options.enabled && options.hilt) {
                if (hiltAvailable) {
                    hiltDaos += fqn
                } else {
                    emit(
                        Diagnostic.HILT_MISSING,
                        "@LogDao(hilt = true) requires Hilt on the compilation classpath.\n" +
                            "Fix: add the Hilt dependencies, or remove `hilt = true`.",
                        symbol,
                    )
                }
            }
            if (options.enabled && options.koin) {
                if (koinAvailable) {
                    koinDaos += fqn
                } else {
                    emit(
                        Diagnostic.KOIN_MISSING,
                        "@LogDao(koin = true) requires Koin on the compilation classpath.\n" +
                            "Fix: add koin-core, or remove `koin = true`.",
                        symbol,
                    )
                }
            }
        }

        val databases = resolver.getSymbolsWithAnnotation(Ks.ROOM_DB_INSPECTOR)
            .filterIsInstance<KSClassDeclaration>()
            .filter { database -> database.containingFile != null }
            .toList()
        for (database in databases) {
            val databaseFqn = database.qualifiedName?.asString() ?: database.simpleName.asString()
            if (databaseFqn in processedDatabases) continue

            val accessorFunctions = daoAccessorFunctions(database)
            exposedDaoFqns += daoAccessorDaos(accessorFunctions)
            if (accessorFunctions.any { fn -> fn.returnType?.resolve()?.let(::typeIsUnresolved) == true }) {
                deferred += database
                continue
            }
            // A wrapper that is still deferred may arrive in a later round; wait
            // for it rather than generating a facade with a missing adapter.
            val pendingDao = daoAccessorDaos(accessorFunctions).any { dao ->
                dao in enabledDaos && dao in deferredInterfaces && dao !in wrappedDaos
            }
            if (pendingDao) {
                deferred += database
                continue
            }

            val accessors = daoAccessors(database, enabledDaos, wrappedDaos, hiltDaos, koinDaos)
            if (accessors.none { accessor -> accessor.wrapped }) continue
            processedDatabases += databaseFqn
            val file = DaoFacade.build(database, accessors)
            file.writeTo(
                environment.codeGenerator,
                Dependencies(aggregating = true, *resolver.getAllFiles().toList().toTypedArray()),
            )
            if (verbose) {
                environment.logger.info(
                    "ilogger-ksp: generated ${file.name} for " +
                        "${accessors.count { it.wrapped }} @LogDao accessor(s) " +
                        "(${database.qualifiedName?.asString()}).",
                )
            }

            // Hilt and Koin each permit exactly one binding per type. Owners are
            // tracked across rounds so a DAO exposed by two databases fails with
            // our diagnostic instead of an opaque duplicate-binding error.
            val hiltAccessors = ArrayList<DaoFacade.Accessor>()
            for (accessor in accessors) {
                if (!accessor.hilt) continue
                val owner = hiltOwners.putIfAbsent(accessor.daoFqn, databaseFqn)
                if (owner == null) {
                    hiltAccessors += accessor
                } else {
                    emit(
                        Diagnostic.DUPLICATE_BINDING,
                        "Duplicate Hilt binding for DAO '${accessor.daoFqn}': it is already " +
                            "bound by '$owner' and cannot also be bound by '$databaseFqn'.\n" +
                            "Fix: keep @LogDao(hilt = true) on only one database, " +
                            "or bind the DAO manually with db.logged(logger).",
                        database,
                    )
                }
            }
            if (hiltAccessors.isNotEmpty()) {
                val hiltFile = HiltBindings.build(database, hiltAccessors)
                hiltFile.writeTo(
                    environment.codeGenerator,
                    Dependencies(aggregating = true, *resolver.getAllFiles().toList().toTypedArray()),
                )
                if (verbose) {
                    environment.logger.info(
                        "ilogger-ksp: generated ${hiltFile.name} for " +
                            "${hiltAccessors.size} Hilt DAO binding(s) " +
                            "($databaseFqn).",
                    )
                }
            }

            val koinAccessors = ArrayList<DaoFacade.Accessor>()
            for (accessor in accessors) {
                if (!accessor.koin) continue
                val owner = koinOwners.putIfAbsent(accessor.daoFqn, databaseFqn)
                if (owner == null) {
                    koinAccessors += accessor
                } else {
                    emit(
                        Diagnostic.DUPLICATE_BINDING,
                        "Duplicate Koin binding for DAO '${accessor.daoFqn}': it is already " +
                            "bound by '$owner' and cannot also be bound by '$databaseFqn'.\n" +
                            "Fix: keep @LogDao(koin = true) on only one database, " +
                            "or bind the DAO manually with db.logged(logger).",
                        database,
                    )
                }
            }
            if (koinAccessors.isNotEmpty()) {
                val koinFile = KoinBindings.build(database, koinAccessors)
                koinFile.writeTo(
                    environment.codeGenerator,
                    Dependencies(aggregating = true, *resolver.getAllFiles().toList().toTypedArray()),
                )
                if (verbose) {
                    environment.logger.info(
                        "ilogger-ksp: generated ${koinFile.name} for " +
                            "${koinAccessors.size} Koin DAO binding(s) " +
                            "($databaseFqn).",
                    )
                }
            }
        }

        // A @LogDao that no database exposes never receives a facade. Wait for
        // rounds to settle so a generated database can still claim it.
        if (deferred.isEmpty()) {
            for ((fqn, declaration) in enabledDaoDeclarations) {
                if (fqn in exposedDaoFqns || !warnedUnusedDaos.add(fqn)) continue
                emit(
                    Diagnostic.UNUSED_LOG_DAO,
                    "@LogDao interface '${declaration.simpleName.asString()}' is not exposed by any @Database " +
                        "accessor in this module, so no database facade is generated.\n" +
                        "Fix: expose it from a @Database, remove @LogDao, or set enabled = false.",
                    declaration,
                )
            }
        }

        // Written once, as soon as no symbol is waiting for a later round, so
        // the diagnostics fixture tests always find a complete report.
        if (expectDiagnostics && !diagnosticsWritten && deferred.isEmpty()) {
            diagnosticsWritten = true
            val combined = resolver.getAllFiles().toList().toTypedArray()
            environment.codeGenerator.createNewFile(
                Dependencies(aggregating = true, *combined),
                packageName = "",
                fileName = "ilogger-diagnostics",
                extensionName = "txt",
            ).bufferedWriter().use { writer ->
                diagnosticLines.forEach { line -> writer.appendLine(line) }
            }
        }
        return deferred.toList()
    }

    // ------------------------------------------------------------------ wrappers

    /**
     * Isolating dependencies: the wrapper is regenerated only when the source
     * files or a file whose declarations it references changes.
     */
    private fun wrapperDependencies(sources: List<KSFile>, ops: List<ResolvedOp>): Dependencies {
        val files = LinkedHashSet<KSFile>()
        files.addAll(sources)
        for (op in ops) {
            files.addType(op.returnType)
            op.extensionReceiverType?.let { files.addType(it) }
            for (parameter in op.parameters) files.addType(parameter.type)
            for (meta in op.metadata) files.addExpr(meta.expr)
            for (change in op.changes) {
                files.addExpr(change.before)
                files.addExpr(change.after)
            }
            files.addExpr(op.entityId)
            files.addExpr(op.actor)
        }
        return Dependencies(aggregating = false, *files.toTypedArray())
    }

    private fun MutableSet<KSFile>.addType(type: KSType) {
        type.declaration.containingFile?.let(::add)
        for (argument in type.arguments) {
            argument.type?.resolve()?.let { addType(it) }
        }
    }

    private fun MutableSet<KSFile>.addExpr(expr: ResolvedExpr?) {
        val chain = when (expr) {
            is ResolvedExpr.Param -> expr.chainInfo
            is ResolvedExpr.Result -> expr.chainInfo
            else -> null
        } ?: return
        for (property in chain.properties) property.containingFile?.let(::add)
    }

    // ------------------------------------------------------------------ action registry

    /**
     * `@LogActions` objects declare the module's canonical action universe.
     * Codes travel as annotation arguments: KSP cannot read property
     * initializers, and referencing the constants keeps one source of truth.
     */
    private fun processActionRegistries(
        resolver: Resolver,
        emit: (Diagnostic, String, Any) -> Unit,
    ) {
        for (symbol in resolver.getSymbolsWithAnnotation(Ks.LOG_ACTIONS_FQN)) {
            val declaration = symbol as? KSClassDeclaration
            if (declaration == null || declaration.classKind != ClassKind.OBJECT) {
                emit(
                    Diagnostic.LOG_ACTIONS_TARGET,
                    "@LogActions can only annotate an object of action constants.\n" +
                        "Fix: declare `object TaskActions { ... }` and list its codes in @LogActions(...).",
                    symbol,
                )
                continue
            }
            val containingFile = declaration.containingFile ?: continue // compiled in another module
            val fqn = declaration.qualifiedName?.asString() ?: continue
            if (!processedActionObjects.add(fqn)) continue

            val annotation = Ks.annotation(declaration, Ks.LOG_ACTIONS_FQN) ?: continue
            val raw = (annotation.arg("actions") as? List<*>).orEmpty().filterIsInstance<String>()
            val accepted = ArrayList<String>(raw.size)
            val seenHere = HashSet<String>()
            for (action in raw) {
                when {
                    action.isBlank() -> emit(
                        Diagnostic.ACTION_GRAMMAR,
                        "@LogActions contains a blank action code.\n" +
                            "Fix: remove the blank entry or declare a canonical code such as 'task.created'.",
                        declaration,
                    )
                    Ks.ACTION_REGEX.matches(action) -> Unit
                    SINGLE_SEGMENT_REGEX.matches(action) -> emit(
                        Diagnostic.SINGLE_SEGMENT_ACTION,
                        "Action '$action' declared by @LogActions has a single segment.\n" +
                            "Fix: use '<domain>.<event>', e.g. 'task.$action'.",
                        declaration,
                    )
                    else -> {
                        emit(
                            Diagnostic.ACTION_GRAMMAR,
                            "Invalid action '$action' declared by @LogActions. Actions must be dotted canonical " +
                                "codes such as 'task.created'.\nFix: use '<domain>.<event>[.<variant>]' with no " +
                                "spaces, quotes or special characters.",
                            declaration,
                        )
                        continue
                    }
                }
                if (!seenHere.add(action)) {
                    if (warnedDuplicateDeclarations.add(action)) {
                        emit(
                            Diagnostic.DUPLICATE_ACTION,
                            "Action '$action' is declared more than once in @LogActions of " +
                                "'${declaration.simpleName.asString()}'.\n" +
                                "Fix: remove the duplicate entry; the generated registry already deduplicates it.",
                            declaration,
                        )
                    }
                    continue
                }
                val owner = declaredActionSources.putIfAbsent(action, declaration.simpleName.asString())
                if (owner != null && owner != declaration.simpleName.asString() &&
                    warnedDuplicateDeclarations.add(action)
                ) {
                    emit(
                        Diagnostic.DUPLICATE_ACTION,
                        "Action '$action' is declared by both '$owner' and " +
                            "'${declaration.simpleName.asString()}' @LogActions registries in this module.\n" +
                            "Fix: keep one canonical registry per code, or suppress ILG062 if the overlap is " +
                            "intentional.",
                        declaration,
                    )
                }
                accepted += action
            }
            val actions = accepted.distinct().sorted()
            declaredActions += actions
            val file = buildActionRegistryFile(declaration, actions)
            file.writeTo(environment.codeGenerator, Dependencies(aggregating = false, containingFile))
        }
    }

    /**
     * Folds one parsed operation into the manifest and enforces the action
     * contract: one schema per action+version, one version per schema.
     */
    private fun recordSchema(
        op: ResolvedOp,
        emit: (Diagnostic, String, Any) -> Unit,
    ) {
        if (declaredActions.isNotEmpty() && op.action !in declaredActions &&
            warnedUndeclaredActions.add(op.action)
        ) {
            emit(
                Diagnostic.UNDECLARED_ACTION,
                "Action '${op.action}' used by '${op.source}' is not declared in any @LogActions registry of " +
                    "this module.\nFix: add the code to the registry object's @LogActions(...) arguments.",
                op.fn,
            )
        }
        val schema = ActionSchema.of(op)
        val key = op.action to op.actionVersion
        val existing = actionSchemas[key]
        if (existing == null) {
            actionSchemas.values.firstOrNull { it.action == op.action && it.sameShape(schema) }?.let { other ->
                emit(
                    Diagnostic.SCHEMA_VERSION_NOISE,
                    "Action '${op.action}' is used at schemaVersion ${other.version} and ${op.actionVersion} " +
                        "with an identical schema.\nFix: keep a single schemaVersion; bump it only when the " +
                        "payload shape changes.",
                    op.fn,
                )
            }
            schema.sources += op.source
            actionSchemas[key] = schema
            return
        }
        if (existing.sameShape(schema)) {
            existing.sources += op.source
            if (existing.sources.size == 2 && warnedDuplicateEmissions.add(op.action)) {
                emit(
                    Diagnostic.DUPLICATE_ACTION,
                    "Action '${op.action}' v${op.actionVersion} is emitted by multiple operations " +
                        "(${existing.sources.joinToString()}). Consumers cannot tell them apart.\n" +
                        "Fix: give each operation a distinct action code, or suppress ILG062 when the shared " +
                        "event contract is intentional.",
                    op.fn,
                )
            }
            return
        }
        emit(
            Diagnostic.SCHEMA_CONFLICT,
            "Action '${op.action}' v${op.actionVersion} is already used with a different schema by " +
                "'${existing.sources.first()}' (${existing.diffFrom(schema)}).\n" +
                "Fix: bump @Log(schemaVersion = ...) when the payload shape changes, or align the selections.",
            op.fn,
        )
    }

    /**
     * Written from [finish] so late-round symbols (generated `@Log`
     * interfaces, registries) are included; [Dependencies.ALL_FILES] makes the
     * resource aggregating. Skipped for modules without actions.
     */
    private fun writeSchemaManifest() {
        if (schemaManifestWritten) return
        if (actionSchemas.isEmpty() && declaredActions.isEmpty()) return
        schemaManifestWritten = true
        val json = renderSchemaManifest(actionSchemas.values, declaredActions)
        environment.codeGenerator
            .createNewFile(Dependencies.ALL_FILES, "META-INF/ilogger", "schema", "json")
            .bufferedWriter()
            .use { it.write(json) }
        val configured = environment.options["ilogger.schema-output"]
        if (!configured.isNullOrBlank()) {
            val relative = File(configured)
            val target = if (relative.isAbsolute) relative else File(System.getProperty("user.dir"), configured)
            target.parentFile?.mkdirs()
            target.writeText(json)
        }
    }

