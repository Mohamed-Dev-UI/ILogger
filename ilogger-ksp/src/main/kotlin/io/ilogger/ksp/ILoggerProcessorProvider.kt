    /**
     * True when any signature or annotation type is an error type. Such
     * symbols are returned to KSP for a later round instead of failing fast,
     * because another processor may generate the missing declarations.
     */
    private fun hasUnresolvedTypes(fn: KSFunctionDeclaration): Boolean {
        fn.returnType?.let { if (typeIsUnresolved(it.resolve())) return true }
        fn.extensionReceiver?.let { if (typeIsUnresolved(it.resolve())) return true }
        for (parameter in fn.parameters) {
            if (typeIsUnresolved(parameter.type.resolve())) return true
        }
        val annotation = Ks.annotation(fn, Ks.LOG_FQN) ?: return false
        return annotation.arguments.any { argument -> valueIsUnresolved(argument.value) }
    }

    private fun valueIsUnresolved(value: Any?): Boolean = when (value) {
        is KSType -> typeIsUnresolved(value)
        is KSAnnotation -> value.arguments.any { argument -> valueIsUnresolved(argument.value) }
        is List<*> -> value.any { element -> valueIsUnresolved(element) }
        else -> false
    }

    private fun typeIsUnresolved(type: KSType, depth: Int = 0): Boolean {
        if (type.isError) return true
        if (depth >= MAX_TYPE_DEPTH) return false
        return type.arguments.any { argument ->
            argument.type?.resolve()?.let { typeIsUnresolved(it, depth + 1) } == true
        }
    }

