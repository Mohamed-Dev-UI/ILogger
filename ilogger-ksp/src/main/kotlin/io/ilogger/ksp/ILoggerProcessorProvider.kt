    /**
     * `@Suppress("ILGxxx")` on the declaration, an enclosing declaration or the
     * file. `"ILG"` and `"ALL"` silence the whole catalog for that scope.
     */
    private fun suppressedAt(symbol: Any, code: String): Boolean {
        val targets = LinkedHashSet<KSAnnotated>()
        var current = symbol as? KSAnnotated
        while (current != null) {
            targets += current
            current = (current as? KSDeclaration)?.parentDeclaration
        }
        (symbol as? KSDeclaration)?.containingFile?.let(targets::add)
        if (symbol is KSFile) targets += symbol
        return targets.any { target ->
            target.suppressionNames().any { name ->
                name.equals(code, ignoreCase = true) ||
                    name.equals("ILG", ignoreCase = true) ||
                    name.equals("ALL", ignoreCase = true)
            }
        }
    }

    private fun KSAnnotated.suppressionNames(): List<String> = annotations
        .filter { annotation -> annotation.shortName.asString() == "Suppress" }
        .flatMap { annotation ->
            annotation.arguments.flatMap { argument ->
                when (val value = argument.value) {
                    is List<*> -> value.filterIsInstance<String>()
                    is String -> listOf(value)
                    else -> emptyList()
                }
            }
        }
        .toList()

    /** Stable source-file label for a symbol carrying a diagnostic. */
    private fun fileLabelOf(symbol: Any): String? = when (symbol) {
        is KSDeclaration -> symbol.containingFile?.fileName
        is KSFile -> symbol.fileName
        else -> null
    }

    /** Room shape detection by qualified name only — no Room dependency anywhere. */
    private fun roomKindOf(fn: KSFunctionDeclaration): String? = when {
        Ks.annotation(fn, Ks.ROOM_INSERT) != null -> "insert"
        Ks.annotation(fn, Ks.ROOM_UPSERT) != null -> "upsert"
        Ks.annotation(fn, Ks.ROOM_UPDATE) != null -> "update"
        Ks.annotation(fn, Ks.ROOM_DELETE) != null -> "delete"
        Ks.annotation(fn, Ks.ROOM_QUERY) != null -> "query"
        Ks.annotation(fn, Ks.ROOM_RAW_QUERY) != null -> "rawquery"
        Ks.annotation(fn, Ks.ROOM_TRANSACTION) != null -> "transaction"
        else -> null
    }

    private fun nodeOf(symbol: Any): com.google.devtools.ksp.symbol.KSNode? =
        symbol as? com.google.devtools.ksp.symbol.KSNode

