package io.ilogger.ksp

import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.CodeBlock
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.ksp.toClassName

/**
 * Generates the optional Koin binding for `@LogDao(koin = true)`:
 *
 * ```kotlin
 * public object AppDatabase_ILogged_KoinModule {
 *     public val module: Module = module {
 *         single<TaskDao> {
 *             get<AppDatabase>().logged(get<ILogger>()).taskDao()
 *         }
 *     }
 * }
 * ```
 *
 * The generated file only references Koin types when the consumer requested
 * the binding and Koin is on its classpath; `ilogger-*` has no Koin dependency.
 */
internal object KoinBindings {

    private val MODULE_TYPE = ClassName("org.koin.core.module", "Module")
    private val MODULE_FUNCTION = MemberName("org.koin.dsl", "module")
    private val ILOGGER_TYPE = ClassName("io.ilogger.core", "ILogger")

    fun build(database: KSClassDeclaration, accessors: List<DaoFacade.Accessor>): FileSpec {
        val databaseType = database.toClassName()
        val moduleName = "${database.simpleName.asString()}_ILogged_KoinModule"

        val definitions = CodeBlock.builder()
            .beginControlFlow("%M", MODULE_FUNCTION)
        for (accessor in accessors.filter { it.koin }) {
            definitions
                .beginControlFlow("single<%T>", accessor.daoType)
                .addStatement(
                    "get<%T>().logged(get<%T>()).%L()",
                    databaseType,
                    ILOGGER_TYPE,
                    accessor.name,
                )
                .endControlFlow()
        }
        definitions.endControlFlow()

        val module = TypeSpec.objectBuilder(moduleName)
            .addKdoc(
                "Koin bindings generated by ilogger-ksp for the `@LogDao(koin = true)`\n" +
                    "interfaces of [%L]. Every definition resolves `%L` and `%T` from Koin\n" +
                    "and returns the wrapped `.logged(logger)` DAO.",
                database.simpleName.asString(),
                database.simpleName.asString(),
                ILOGGER_TYPE,
            )
            .addProperty(
                PropertySpec.builder("module", MODULE_TYPE, KModifier.PUBLIC)
                    .initializer(definitions.build())
                    .build(),
            )
            .build()

        return FileSpec.builder(database.packageName.asString(), moduleName)
            .addFileComment("Generated by ilogger-ksp from @LogDao(koin = true). DO NOT MODIFY.\n")
            .addType(module)
            .build()
    }
}
