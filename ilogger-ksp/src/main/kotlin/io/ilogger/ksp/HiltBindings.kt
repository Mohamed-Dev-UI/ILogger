package io.ilogger.ksp

import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.ksp.toClassName

/**
 * Generates the optional Hilt binding for `@LogDao(hilt = true)`:
 *
 * ```kotlin
 * @Module
 * @InstallIn(SingletonComponent::class)
 * public object AppDatabase_ILogged_HiltModule {
 *     @Provides @Singleton
 *     public fun taskDao(db: AppDatabase, logger: ILogger): TaskDao =
 *         db.logged(logger).taskDao()
 * }
 * ```
 *
 * The module is generated in the consumer's compilation, so `ilogger-*` never
 * depends on Hilt. Only public DAOs/databases are bound; internal ones cannot
 * be exposed by a public provider.
 */
internal object HiltBindings {

    private val MODULE = ClassName("dagger", "Module")
    private val PROVIDES = ClassName("dagger", "Provides")
    private val INSTALL_IN = ClassName("dagger.hilt", "InstallIn")
    private val SINGLETON_COMPONENT = ClassName("dagger.hilt.components", "SingletonComponent")
    private val SINGLETON = ClassName("javax.inject", "Singleton")
    private val ILOGGER_TYPE = ClassName("io.ilogger.core", "ILogger")

    fun build(database: KSClassDeclaration, accessors: List<DaoFacade.Accessor>): FileSpec {
        val databaseType = database.toClassName()
        val moduleName = "${database.simpleName.asString()}_ILogged_HiltModule"

        val module = TypeSpec.objectBuilder(moduleName)
            .addKdoc(
                "Hilt bindings generated by ilogger-ksp for the `@LogDao(hilt = true)`\n" +
                    "interfaces of [%L]. Every provider returns the wrapped\n" +
                    "`.logged(logger)` DAO; the database and logger come from the graph.",
                database.simpleName.asString(),
            )
            .addAnnotation(MODULE)
            .addAnnotation(
                AnnotationSpec.builder(INSTALL_IN)
                    .addMember("%T::class", SINGLETON_COMPONENT)
                    .build(),
            )
            .apply {
                for (accessor in accessors.filter { it.hilt }) {
                    addFunction(
                        FunSpec.builder(accessor.name)
                            .addAnnotation(PROVIDES)
                            .addAnnotation(SINGLETON)
                            .returns(accessor.daoType)
                            .addParameter("db", databaseType)
                            .addParameter("logger", ILOGGER_TYPE)
                            .addStatement("return db.logged(logger).%L()", accessor.name)
                            .build(),
                    )
                }
            }
            .build()

        return FileSpec.builder(database.packageName.asString(), moduleName)
            .addFileComment("Generated by ilogger-ksp from @LogDao(hilt = true). DO NOT MODIFY.\n")
            .addType(module)
            .build()
    }
}
