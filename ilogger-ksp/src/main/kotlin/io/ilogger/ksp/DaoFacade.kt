package io.ilogger.ksp

import com.google.devtools.ksp.symbol.KSClassDeclaration
import com.google.devtools.ksp.symbol.Modifier
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.TypeName
import com.squareup.kotlinpoet.TypeSpec
import com.squareup.kotlinpoet.ksp.toClassName

/**
 * Generates the per-database facade behind `@LogDao`:
 *
 * ```kotlin
 * public class AppDatabase_ILogged internal constructor(
 *     private val db: AppDatabase,
 *     private val logger: ILogger,
 * ) {
 *     public val database: AppDatabase get() = db
 *     public fun taskDao(): TaskDao = db.taskDao().logged(logger)
 *     public fun logDao(): RoomLogDao = db.logDao()   // not opted in
 * }
 *
 * public fun AppDatabase.logged(logger: ILogger): AppDatabase_ILogged =
 *     AppDatabase_ILogged(db = this, logger = logger)
 * ```
 *
 * The facade is a thin delegate: it adds no state beyond the database and the
 * logger, and every non-opted-in accessor passes straight through. It is
 * generated only for databases that expose at least one opted-in DAO.
 */
internal object DaoFacade {

    private val ILOGGER_TYPE = ClassName("io.ilogger.core", "ILogger")

    /** One no-argument DAO accessor declared on the database. */
    internal class Accessor(
        val name: String,
        val daoType: TypeName,
        val daoFqn: String,
        val wrapped: Boolean,
        /** An internal DAO must not be exposed by a public facade method. */
        val internalDao: Boolean,
        /** Opted into the optional Hilt binding. */
        val hilt: Boolean,
        /** Opted into the optional Koin binding. */
        val koin: Boolean,
    )

    fun build(database: KSClassDeclaration, accessors: List<Accessor>): FileSpec {
        val databaseType = database.toClassName()
        val facadeName = "${database.simpleName.asString()}_ILogged"
        val facadeType = ClassName(database.packageName.asString(), facadeName)
        val visibility = if (Modifier.INTERNAL in database.modifiers) KModifier.INTERNAL else KModifier.PUBLIC

        val classBuilder = TypeSpec.classBuilder(facadeName)
            .addModifiers(visibility)
            .addKdoc(
                "Generated by ilogger-ksp for the `@LogDao` interfaces of [%L].\n\n" +
                    "Obtain it with `%L.logged(logger)`; opted-in DAO accessors return\n" +
                    "the `.logged(logger)` adapter, all others pass through unchanged.",
                database.simpleName.asString(),
                database.simpleName.asString(),
            )
            .primaryConstructor(
                FunSpec.constructorBuilder()
                    .addModifiers(KModifier.INTERNAL)
                    .addParameter("db", databaseType)
                    .addParameter("logger", ILOGGER_TYPE)
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("db", databaseType, KModifier.PRIVATE)
                    .initializer("db")
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("logger", ILOGGER_TYPE, KModifier.PRIVATE)
                    .initializer("logger")
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("database", databaseType)
                    .addKdoc("The underlying database, for transactions and lifecycle calls.")
                    .getter(FunSpec.getterBuilder().addStatement("return db").build())
                    .build(),
            )

        for (accessor in accessors) {
            classBuilder.addFunction(
                FunSpec.builder(accessor.name)
                    .addModifiers(if (accessor.internalDao) KModifier.INTERNAL else KModifier.PUBLIC)
                    .returns(accessor.daoType)
                    .addStatement(
                        "return db.%L()%L",
                        accessor.name,
                        if (accessor.wrapped) ".logged(logger)" else "",
                    )
                    .build(),
            )
        }

        return FileSpec.builder(database.packageName.asString(), facadeName)
            .addFileComment("Generated by ilogger-ksp from @LogDao. DO NOT MODIFY.\n")
            .addType(classBuilder.build())
            .addFunction(
                FunSpec.builder("logged")
                    .addModifiers(visibility)
                    .receiver(databaseType)
                    .returns(facadeType)
                    .addParameter("logger", ILOGGER_TYPE)
                    .addKdoc(
                        "Wraps every `@LogDao`-enabled DAO of this database with its\n" +
                            "generated `.logged(logger)` adapter; other accessors pass through.",
                    )
                    .addStatement("return %T(db = this, logger = logger)", facadeType)
                    .build(),
            )
            .build()
    }
}
