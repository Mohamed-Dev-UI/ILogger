/**
 * KotlinPoet-based generation of the delegating wrapper for one interface.
 *
 * The generated shape for `interface TaskDao`:
 *
 * ```kotlin
 * internal class TaskDao_ILogger(
 *     delegate: TaskDao,
 *     logger: ILogger,
 * ) : TaskDao by delegate {
 *     // overrides for @Log functions only — everything else passes through
 * }
 *
 * public fun TaskDao.logged(logger: ILogger): TaskDao = TaskDao_ILogger(this, logger)
 * ```
 *
 * Event emission per `@Log` function (in order): optional START event, the
 * delegate call, the SUCCESS event with the operation result in scope, and —
 * only when [Log.onFailure] is enabled — a FAILURE event inside a nested
 * try/catch whose dispatch error is suppressed onto the original exception
 * (failures are never swallowed).
 */
internal object Codegen {

    /**
     * Local names for one generated body. User parameter names may collide with
     * any fixed local (`result`, `context`, `error`, ...), so each name is
     * suffixed until it is free. Parameter references themselves resolve by
     * index, never by matching these names.
     */
    private class LocalNames(parameterNames: Collection<String>) {
        private val taken: MutableSet<String> = parameterNames.toMutableSet()

        private fun pick(base: String): String {
            var name = base
            while (!taken.add(name)) name += "_"
            return name
        }

        val ctx: String = pick("iloggerCtx")
        val result: String = pick("iloggerResult")
        val error: String = pick("iloggerError")
        val cancellation: String = pick("iloggerCancellation")
        val dispatchError: String = pick("iloggerDispatchError")
        val logger: String = pick("logger")
        val upstream: String = pick("iloggerUpstream")
        val cause: String = pick("iloggerCause")
        val changeBefore: String = pick("iloggerChangeBefore")
        val changeAfter: String = pick("iloggerChangeAfter")
    }

    private val ILogger_TYPE = ClassName("io.ilogger.core", "ILogger")
    private val OUTCOME_TYPE = ClassName("io.ilogger.core", "Outcome")
    private val LOG_LEVEL_TYPE = ClassName("io.ilogger.annotations", "LogLevel")
    private val DISPATCH_TYPE = ClassName("io.ilogger.annotations", "DispatchMode")
    private val ACTOR_TYPE = ClassName("io.ilogger.core", "Actor")
    private val MASKING_TYPE = ClassName("io.ilogger.core", "LogMasking")
    private val FIELD_CHANGE_TYPE = ClassName("io.ilogger.core", "FieldChange")
    private val CONTEXTS_TYPE = ClassName("io.ilogger.core", "LogContexts")
    private val CANCELLATION_TYPE = ClassName("kotlin.coroutines.cancellation", "CancellationException")
    private val THROWABLE_TYPE = ClassName("kotlin", "Throwable")
    private val ON_START = MemberName("kotlinx.coroutines.flow", "onStart")
    private val ON_COMPLETION = MemberName("kotlinx.coroutines.flow", "onCompletion")
    private val LAZY_MODE = ClassName("kotlin", "LazyThreadSafetyMode")

    fun buildInterfaceFile(interfaceDecl: KSClassDeclaration, ops: List<ResolvedOp>): FileSpec {
        val interfaceName = interfaceDecl.simpleName.asString()
        val wrapperName = "${interfaceName}_ILogger"
        val typeResolver = interfaceDecl.typeParameters.toTypeParameterResolver()
        val typeVariables = interfaceDecl.typeParameters.map { it.toTypeVariableName(typeResolver) }
        val interfaceType: TypeName =
            if (typeVariables.isEmpty()) interfaceDecl.toClassName()
            else interfaceDecl.toClassName().parameterizedBy(typeVariables)
        val file = FileSpec.builder(interfaceDecl.packageName.asString(), wrapperName)
            .addFileComment("Generated by ilogger-ksp from @Log annotations. DO NOT MODIFY.\n")

        val classBuilder = TypeSpec.classBuilder(wrapperName)
            .addModifiers(KModifier.INTERNAL)
            .addTypeVariables(typeVariables)
            .primaryConstructor(
                FunSpec.constructorBuilder()
                    .addParameter(ParameterSpec.builder("iloggerDelegate", interfaceType).build())
                    .addParameter(ParameterSpec.builder("logger", ILogger_TYPE).build())
                    .build(),
            )
            .addSuperinterface(interfaceType, "iloggerDelegate")
            // Same-name properties collapse into the primary constructor as
            // `private val` parameters (KotlinPoet correlation), making the
            // delegate referenceable from member bodies.
            .addProperty(
                PropertySpec.builder("iloggerDelegate", interfaceType, KModifier.PRIVATE)
                    .initializer("iloggerDelegate")
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("logger", ILogger_TYPE, KModifier.PRIVATE)
                    .initializer("logger")
                    .build(),
            )

        // Shared extractor instances, deduped across operations of this interface.
        val extractorFields = addExtractorFields(classBuilder, ops)

        for (op in ops) {
            classBuilder.addFunction(
                buildOverride(op, extractorFields, "this.iloggerDelegate", typeResolver, wrapperName),
            )
        }

        file.addType(classBuilder.build())
        file.addFunction(
            FunSpec.builder("logged")
                .addTypeVariables(typeVariables)
                .receiver(interfaceType)
                .returns(interfaceType)
                .addParameter("logger", ILogger_TYPE)
                .addStatement("return %L(iloggerDelegate = this, logger = logger)", wrapperName)
                .build(),
        )
        return file.build()
    }

    /**
     * Subclass wrapper for an open/abstract class. There is no instance proxy
     * in Kotlin: the wrapper participates in construction, forwards the primary
     * constructor, and overrides open members delegating via `super`.
     */
    fun buildClassFile(classDecl: KSClassDeclaration, ops: List<ResolvedOp>): FileSpec {
        val className = classDecl.simpleName.asString()
        val wrapperName = "${className}_ILogger"
        val file = FileSpec.builder(classDecl.packageName.asString(), wrapperName)
            .addFileComment("Generated by ilogger-ksp from @Log annotations. DO NOT MODIFY.\n")

        val typeResolver = classDecl.typeParameters.toTypeParameterResolver()
        val typeVariables = classDecl.typeParameters.map { it.toTypeVariableName(typeResolver) }

        // Forward the primary constructor; parameters are renamed only when they
        // collide with the injected logger parameter or each other. Vararg
        // parameters are spread at the super call.
        val ctor = classDecl.primaryConstructor
        data class Forward(val name: String, val type: TypeName, val vararg: Boolean)
        val forwarded = ArrayList<Forward>(ctor?.parameters?.size ?: 0)
        if (ctor != null) {
            val taken = mutableSetOf("logger")
            for (param in ctor.parameters) {
                var name = param.name?.asString() ?: "iloggerArg${forwarded.size}"
                while (!taken.add(name)) name += "_"
                forwarded += Forward(name, param.type.toTypeName(typeResolver), param.isVararg)
            }
        }

        val classBuilder = TypeSpec.classBuilder(wrapperName)
            .addModifiers(KModifier.INTERNAL)
            .addModifiers(
                if (Modifier.ABSTRACT in classDecl.modifiers) KModifier.ABSTRACT else KModifier.OPEN,
            )
            .addTypeVariables(typeVariables)
            .superclass(
                if (typeVariables.isEmpty()) classDecl.toClassName()
                else classDecl.toClassName().parameterizedBy(typeVariables),
            )
            .primaryConstructor(
                FunSpec.constructorBuilder()
                    .addParameter(ParameterSpec.builder("logger", ILogger_TYPE).build())
                    .apply {
                        for (param in forwarded) addParameter(ParameterSpec.builder(param.name, param.type).build())
                    }
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("logger", ILogger_TYPE, KModifier.PRIVATE)
                    .initializer("logger")
                    .build(),
            )
        for (param in forwarded) {
            classBuilder.addSuperclassConstructorParameter(
                if (param.vararg) "*${param.name}" else param.name,
            )
        }

        val extractorFields = addExtractorFields(classBuilder, ops)
        for (op in ops) {
            classBuilder.addFunction(buildOverride(op, extractorFields, "super", typeResolver, wrapperName))
        }

        file.addType(classBuilder.build())
        return file.build()
    }

    /**
     * Adapter wrappers for top-level `@Log` functions. Plain functions get a
     * public `<Name>_ILogger` object whose members take the logger first;
     * extension functions get a same-name extension taking the logger first.
     * Bodies call the original by its plain name — the same resolution a user
     * call site in this package would perform (member candidates carry one
     * extra parameter and never match the delegate call).
     */
    fun buildTopLevelFile(ops: List<ResolvedOp>): FileSpec {
        val first = ops.first()
        val packageName = first.containerPackage
        val fnName = first.fn.simpleName.asString()
        val wrapperName = fnName.replaceFirstChar { it.uppercaseChar() } + "_ILogger"
        val file = FileSpec.builder(packageName, wrapperName)
            .addFileComment("Generated by ilogger-ksp from @Log annotations. DO NOT MODIFY.\n")

        val plainOps = ArrayList<ResolvedOp>()
        val extensionOps = ArrayList<ResolvedOp>()
        for (op in ops) {
            if (op.extensionReceiverType != null) extensionOps += op else plainOps += op
        }

        if (plainOps.isNotEmpty()) {
            val objectBuilder = TypeSpec.objectBuilder(wrapperName)
                .addModifiers(KModifier.PUBLIC)
            val extractorFields = addExtractorFields(objectBuilder, plainOps, throughLogger = false)
            for (op in plainOps) {
                objectBuilder.addFunction(topLevelWrapper(op, extractorFields))
            }
            file.addType(objectBuilder.build())
        }
        for (op in extensionOps) {
            file.addFunction(topLevelWrapper(op, emptyMap()))
        }
        return file.build()
    }

    private fun topLevelWrapper(op: ResolvedOp, extractorFields: Map<String, String>): FunSpec {
        val extension = op.extensionReceiverType != null
        val locals = LocalNames(op.parameters.map { it.name })
        val typeResolver = op.fn.typeParameters.toTypeParameterResolver()
        val builder = FunSpec.builder(op.fn.simpleName.asString())
            .addModifiers(KModifier.PUBLIC)
            .addTypeVariables(op.fn.typeParameters.map { typeResolver[it.name.getShortName()] })
            .returns(op.returnType.toTypeName(typeResolver))
        if (op.suspendFn) builder.addModifiers(KModifier.SUSPEND)
        if (extension) builder.receiver(op.extensionReceiverType!!.toTypeName(typeResolver))
        builder.addParameter(ParameterSpec.builder(locals.logger, ILogger_TYPE).build())
        for (parameter in op.parameters) {
            val spec = ParameterSpec.builder(parameter.name, parameter.type.toTypeName(typeResolver))
            if (parameter.vararg) spec.addModifiers(KModifier.VARARG)
            builder.addParameter(spec.build())
        }
        if (op.description.isNotBlank()) {
            builder.addKdoc("%L\n", op.description)
        }
        val delegate = if (extension) {
            CodeBlock.of("this.%L(%L)", op.fn.simpleName.asString(), argList(op))
        } else {
            CodeBlock.of("%L(%L)", op.fn.simpleName.asString(), argList(op))
        }
        builder.addCode(
            if (Ks.isFlow(op.returnType)) {
                flowBody(op, extractorFields, locals, delegate, locals.logger, null)
            } else {
                body(op, extractorFields, locals, delegate, locals.logger)
            },
        )
        return builder.build()
    }

    /**
     * Shared converter instances, deduped across the operations of one type.
     *
     * Extractors resolve once through the logger's `ExtractorRegistry` (a
     * registered factory wins; otherwise the generated no-argument fallback or
     * object reference is used) and are wrapped in `validated()` at the call
     * site. Adapters are still constructed directly. Top-level wrappers have
     * no instance to host fields, so they resolve inline ([throughLogger] =
     * false skips extractor fields there).
     */
    private fun addExtractorFields(
        typeBuilder: TypeSpec.Builder,
        ops: List<ResolvedOp>,
        throughLogger: Boolean = true,
    ): Map<String, String> {
        val extractorFields = HashMap<String, String>() // fqn -> field name
        var converterIndex = 0

        // A class is resolved once per wrapper: if any use opts into
        // registration, the shared field requires it for all uses.
        val extractorSpecs = LinkedHashMap<String, Pair<Boolean, Boolean>>() // fqn -> (injected, isObject)
        for (op in ops) {
            for (meta in op.metadata) {
                val fqn = meta.extractorFqn ?: continue
                val prior = extractorSpecs[fqn]
                extractorSpecs[fqn] =
                    (prior?.first == true || meta.extractorInjected) to meta.extractorIsObject
            }
        }

        fun registerAdapter(fqn: String) {
            if (extractorFields.containsKey(fqn)) return
            extractorFields[fqn] = "iloggerConverter${converterIndex++}"
            typeBuilder.addProperty(
                PropertySpec.builder(extractorFields.getValue(fqn), ClassName.bestGuess(fqn), KModifier.PRIVATE)
                    .initializer(CodeBlock.of("%T()", ClassName.bestGuess(fqn)))
                    .build(),
            )
        }

        fun registerExtractor(fqn: String) {
            if (extractorFields.containsKey(fqn)) return
            val fieldName = "iloggerConverter${converterIndex++}"
            extractorFields[fqn] = fieldName
            val (injected, isObject) = extractorSpecs.getValue(fqn)
            val type = ClassName.bestGuess(fqn)
            val resolution = if (injected) {
                CodeBlock.of("logger.extractors.require(%T::class)", type)
            } else {
                val fallback = if (isObject) CodeBlock.of("%T", type) else CodeBlock.of("%T()", type)
                CodeBlock.of("logger.extractors.get(%T::class) { %L }", type, fallback)
            }
            typeBuilder.addProperty(
                PropertySpec.builder(fieldName, type, KModifier.PRIVATE)
                    .delegate(CodeBlock.of("lazy(%T.PUBLICATION) { %L }", LAZY_MODE, resolution))
                    .build(),
            )
        }

        for (op in ops) {
            for (meta in op.metadata) {
                meta.adapterFqn?.let(::registerAdapter)
                if (throughLogger) meta.extractorFqn?.let(::registerExtractor)
            }
        }
        return extractorFields
    }

    private fun buildOverride(
        op: ResolvedOp,
        extractorFields: Map<String, String>,
        delegateTarget: String,
        containerResolver: TypeParameterResolver,
        wrapperName: String,
    ): FunSpec {
        val locals = LocalNames(op.parameters.map { it.name })
        val typeResolver = op.fn.typeParameters.toTypeParameterResolver(parent = containerResolver)
        val builder = FunSpec.builder(op.fn.simpleName.asString())
            .addModifiers(KModifier.OVERRIDE)
            .addTypeVariables(op.fn.typeParameters.map { typeResolver[it.name.getShortName()] })
            .returns(op.returnType.toTypeName(typeResolver))
        if (op.suspendFn) builder.addModifiers(KModifier.SUSPEND)
        for (parameter in op.parameters) {
            val spec = ParameterSpec.builder(parameter.name, parameter.type.toTypeName(typeResolver))
            if (parameter.vararg) spec.addModifiers(KModifier.VARARG)
            builder.addParameter(spec.build())
        }
        if (op.description.isNotBlank()) {
            builder.addKdoc("%L\n", op.description)
        }
        val delegate = delegateCall(op, delegateTarget)
        builder.addCode(
            if (Ks.isFlow(op.returnType)) {
                flowBody(op, extractorFields, locals, delegate, "this@$wrapperName.logger", wrapperName)
            } else {
                body(op, extractorFields, locals, delegate, "this.logger")
            },
        )
        return builder.build()
    }

    private fun body(
        op: ResolvedOp,
        extractorFields: Map<String, String>,
        locals: LocalNames,
        delegate: CodeBlock,
        loggerAccess: String,
    ): CodeBlock {
        val block = CodeBlock.builder()
        // Fast path: instrumentation is off — plain delegation, zero allocation.
        block.add("if (!%L.enabled) return %L\n", loggerAccess, delegate)
        if (op.needsContextLocal) {
            val accessor = if (op.suspendFn) "current()" else "currentThread()"
            block.addStatement("val %L = %T.%L", locals.ctx, CONTEXTS_TYPE, accessor)
        }
        if (op.before) {
            block.add(recordCall(op, EventKind.START, extractorFields, locals, usesResult = false, loggerAccess))
        }
        // Cancellation is control flow, not a business failure: it is caught
        // first so it never reaches the FAILURE branch. SKIP rethrows without
        // touching the logger; LOG records through recordNow (non-suspending,
        // ASYNC) so a cancelled coroutine can never block or fail on logging.
        val logCancellation = op.suspendFn && op.onCancellation == "LOG"
        val needsTry = op.onFailure || logCancellation
        if (needsTry) block.beginControlFlow("try")
        if (op.unitReturn) {
            block.add("%L\n", delegate)
        } else {
            block.addStatement("val %L = %L", locals.result, delegate)
        }
        if (op.onSuccess) {
            block.add(recordCall(op, EventKind.SUCCESS, extractorFields, locals, usesResult = true, loggerAccess))
        }
        if (!op.unitReturn) block.addStatement("return %L", locals.result)
        if (needsTry) {
            if (op.suspendFn) {
                block.nextControlFlow("catch (%L: %T)", locals.cancellation, CANCELLATION_TYPE)
                if (logCancellation) {
                    block.beginControlFlow("try")
                    block.add(
                        recordCall(
                            op,
                            EventKind.CANCELLATION,
                            extractorFields,
                            locals,
                            usesResult = false,
                            loggerAccess,
                            methodOverride = "recordNow",
                            failureVar = locals.cancellation,
                        ),
                    )
                    block.nextControlFlow("catch (%L: %T)", locals.dispatchError, THROWABLE_TYPE)
                    block.addStatement("%L.addSuppressed(%L)", locals.cancellation, locals.dispatchError)
                    block.endControlFlow()
                }
                block.addStatement("throw %L", locals.cancellation)
            }
            if (op.onFailure) {
                block.nextControlFlow("catch (%L: %T)", locals.error, THROWABLE_TYPE)
                // Failure events must never mask or swallow the original error.
                block.beginControlFlow("try")
                block.add(
                    recordCall(
                        op,
                        EventKind.FAILURE,
                        extractorFields,
                        locals,
                        usesResult = false,
                        loggerAccess,
                        failureVar = locals.error,
                    ),
                )
                block.nextControlFlow("catch (%L: %T)", locals.dispatchError, THROWABLE_TYPE)
                block.addStatement("%L.addSuppressed(%L)", locals.error, locals.dispatchError)
                block.endControlFlow()
                block.addStatement("throw %L", locals.error)
            }
            block.endControlFlow()
        }
        return block.build()
    }

    private enum class EventKind { START, SUCCESS, FAILURE, CANCELLATION }

    /**
     * Body for Flow-returning functions: the wrapper is a cold flow transform.
     * Events: START at subscription (onStart), SUCCESS on normal completion,
     * FAILURE on stream error, cancellation per onCancellation. All records use
     * the suspend record API (the hooks are suspend) except cancellation, which
     * must never suspend inside a cancelled coroutine.
     */
    private fun flowBody(
        op: ResolvedOp,
        extractorFields: Map<String, String>,
        locals: LocalNames,
        delegate: CodeBlock,
        loggerAccess: String,
        thisQualifier: String?,
    ): CodeBlock {
        val block = CodeBlock.builder()
        block.addStatement("val %L = %L", locals.upstream, delegate)
        // Fast path: instrumentation is off — the raw upstream flows through.
        block.add("if (!%L.enabled) return %L\n", loggerAccess, locals.upstream)
        // The operator chain continues the return expression (leading-dot
        // continuation), so the wrapper returns the transformed flow.
        block.add("return %L\n", locals.upstream)
        if (op.before) {
            block.add(".%M {\n", ON_START)
            block.indent()
            if (op.needsContextLocal) {
                block.addStatement("val %L = %T.current()", locals.ctx, CONTEXTS_TYPE)
            }
            block.add(
                recordCall(
                    op,
                    EventKind.START,
                    extractorFields,
                    locals,
                    usesResult = true,
                    loggerAccess,
                    methodOverride = "record",
                    thisQualifier = thisQualifier,
                ),
            )
            block.unindent()
            block.add("}\n")
        }
        val logCancellation = op.onCancellation == "LOG"
        if (op.onSuccess || op.onFailure || logCancellation) {
            block.add(".%M { %L ->\n", ON_COMPLETION, locals.cause)
            block.indent()
            block.beginControlFlow("when")
            if (op.onSuccess) {
                block.beginControlFlow("%L == null ->", locals.cause)
                if (op.needsContextLocal) {
                    // cause == null means the collection finished normally — the
                    // suspend context is readable here.
                    block.addStatement("val %L = %T.current()", locals.ctx, CONTEXTS_TYPE)
                }
                block.add(
                    recordCall(
                        op,
                        EventKind.SUCCESS,
                        extractorFields,
                        locals,
                        usesResult = true,
                        loggerAccess,
                        methodOverride = "record",
                        thisQualifier = thisQualifier,
                    ),
                )
                block.endControlFlow()
            }
            // Always present: a cancellation must not fall into the failure branch.
            block.beginControlFlow("%L is %T ->", locals.cause, CANCELLATION_TYPE)
            if (logCancellation) {
                if (op.needsContextLocal) {
                    // A cancelled coroutine cannot suspend — thread-local bridge only.
                    block.addStatement("val %L = %T.currentThread()", locals.ctx, CONTEXTS_TYPE)
                }
                block.add(
                    recordCall(
                        op,
                        EventKind.CANCELLATION,
                        extractorFields,
                        locals,
                        usesResult = true,
                        loggerAccess,
                        methodOverride = "recordNow",
                        failureVar = locals.cause,
                    ),
                )
            }
            block.endControlFlow()
            if (op.onFailure) {
                block.beginControlFlow("else ->")
                // Failure records must never mask the stream error.
                block.beginControlFlow("try")
                if (op.needsContextLocal) {
                    block.addStatement("val %L = %T.current()", locals.ctx, CONTEXTS_TYPE)
                }
                block.add(
                    recordCall(
                        op,
                        EventKind.FAILURE,
                        extractorFields,
                        locals,
                        usesResult = true,
                        loggerAccess,
                        methodOverride = "record",
                        failureVar = locals.cause,
                        thisQualifier = thisQualifier,
                    ),
                )
                block.nextControlFlow("catch (%L: %T)", locals.dispatchError, THROWABLE_TYPE)
                block.addStatement("%L.addSuppressed(%L)", locals.cause, locals.dispatchError)
                block.endControlFlow()
                block.addStatement("throw %L", locals.cause)
                block.endControlFlow()
            }
            block.endControlFlow()
            block.unindent()
            block.add("}\n")
        }
        return block.build()
    }

    private fun argList(op: ResolvedOp): String =
        op.parameters.joinToString(", ") { parameter ->
            if (parameter.vararg) "*${parameter.name}" else parameter.name
        }

    private fun delegateCall(op: ResolvedOp, target: String): CodeBlock =
        CodeBlock.of("%L.%L(%L)", target, op.fn.simpleName.asString(), argList(op))

    private fun recordCall(
        op: ResolvedOp,
        kind: EventKind,
        extractorFields: Map<String, String>,
        locals: LocalNames,
        usesResult: Boolean,
        loggerAccess: String,
        methodOverride: String? = null,
        failureVar: String? = null,
        thisQualifier: String? = null,
    ): CodeBlock {
        val block = CodeBlock.builder()
        val recordMethod = methodOverride ?: if (op.suspendFn) "record" else "recordNow"
        block.add("%L.%L(\n", loggerAccess, recordMethod).indent()
        block.add("action = %S,\n", op.action)
        block.add("actionVersion = %L,\n", op.actionVersion)
        block.add("level = %T.%L,\n", LOG_LEVEL_TYPE, op.level)
        op.entityName?.let { block.add("entity = %S,\n", it) }

        // Entity id: result-derived ids only exist on SUCCESS events.
        op.entityId?.takeIf { it !is ResolvedExpr.None }?.let { idExpr ->
            if (!idExpr.usesResult || usesResult) {
                block.add(
                    "entityId = %L,\n",
                    renderValue(idExpr, op, RenderPurpose.ID, extractorFields, locals),
                )
            }
        }

        // Explicit actor override; ambient actor wins when absent (record's precedence).
        op.actor?.let { actorExpr ->
            if (!actorExpr.usesResult || usesResult) {
                val purpose = when (op.actorSensitiveMode) {
                    SensitiveMode.META_MASK -> RenderPurpose.MASK
                    SensitiveMode.META_HASH -> RenderPurpose.HASH
                    else -> RenderPurpose.ACTOR_ID
                }
                val id = renderValue(actorExpr, op, purpose, extractorFields, locals)
                block.add("actor = %L?.let { %T.user(it) },\n", id, ACTOR_TYPE)
            }
        }

        when (kind) {
            EventKind.SUCCESS -> Unit // SUCCESS is the default outcome
            EventKind.START -> block.add("outcome = %T.START,\n", OUTCOME_TYPE)
            EventKind.FAILURE, EventKind.CANCELLATION -> {
                block.add("outcome = %T.FAILURE,\n", OUTCOME_TYPE)
                block.add("failure = %L,\n", requireNotNull(failureVar))
            }
        }

        // Metadata: result-derived entries are absent on START/FAILURE events.
        val metadata = op.metadata.filter { !it.expr.usesResult || usesResult }
        if (metadata.isNotEmpty()) {
            block.add("metadata = mapOf(\n").indent()
            for (meta in metadata) {
                val value = renderMetaValue(meta, op, extractorFields, locals, thisQualifier)
                block.add("%S to %L,\n", meta.name, value)
            }
            block.unindent().add("),\n")
        }

        // Changes are recorded on success only: START has no after-values yet and
        // FAILURE would misrepresent an unapplied change as applied.
        if (kind == EventKind.SUCCESS && op.changes.isNotEmpty()) {
            block.add("changes = listOfNotNull(\n").indent()
            for (change in op.changes) {
                val before = renderValue(change.before, op, RenderPurpose.PLAIN, extractorFields, locals)
                val after = renderValue(change.after, op, RenderPurpose.PLAIN, extractorFields, locals)
                if (change.onlyIfChanged) {
                    // A scoped block lets both expressions evaluate once even
                    // when they read the result or a mutable property.
                    block.add("run {\n").indent()
                    block.addStatement("val %L = %L", locals.changeBefore, before)
                    block.addStatement("val %L = %L", locals.changeAfter, after)
                    block.add(
                        "if (%L) %T(field = %S, before = %L, after = %L) else null\n",
                        changedComparison(change, op, locals),
                        FIELD_CHANGE_TYPE,
                        change.field,
                        locals.changeBefore,
                        locals.changeAfter,
                    )
                    block.unindent().add("},\n")
                } else {
                    block.add(
                        "%T(field = %S, before = %L, after = %L),\n",
                        FIELD_CHANGE_TYPE,
                        change.field,
                        before,
                        after,
                    )
                }
            }
            block.unindent().add("),\n")
        }

        block.add("source = %S,\n", op.source)
        if (op.category.isNotBlank()) block.add("category = %S,\n", op.category)
        if (kind == EventKind.CANCELLATION) {
            // recordNow's default is ASYNC, but emit it explicitly: a cancelled
            // coroutine must not block on INLINE delivery.
            block.add("dispatch = %T.ASYNC,\n", DISPATCH_TYPE)
        } else if (op.suspendFn) {
            if (op.dispatch != "DEFAULT") block.add("dispatch = %T.%L,\n", DISPATCH_TYPE, op.dispatch)
        } else {
            // recordNow's own default is ASYNC; emit the mode explicitly so
            // DispatchMode.DEFAULT still resolves to the configured dispatch.
            block.add("dispatch = %T.%L,\n", DISPATCH_TYPE, op.dispatch)
        }
        if (op.sampling != -1.0) block.add("sampling = %L,\n", op.sampling)
        block.unindent().add(")\n")
        return block.build()
    }

    private fun renderMetaValue(
        meta: ResolvedMeta,
        op: ResolvedOp,
        extractorFields: Map<String, String>,
        locals: LocalNames,
        thisQualifier: String? = null,
    ): CodeBlock {
        val purpose = when (meta.sensitiveMode) {
            SensitiveMode.META_MASK -> RenderPurpose.MASK
            SensitiveMode.META_HASH -> RenderPurpose.HASH
            else -> RenderPurpose.PLAIN
        }
        val value = renderValue(meta.expr, op, purpose, extractorFields, locals)
        val extractorField = meta.extractorFqn?.let { extractorFields[it] }
        val adapterField = meta.adapterFqn?.let { extractorFields[it] }
        // Converter inputs are rendered nullable-safe: a null chain yields null
        // metadata (the converter never runs on null). Converter metas are
        // always PLAIN purpose — MASK/HASH combinations are rejected at parse.
        return when {
            // Adapters render through ValueAdapter.render; the qualified-this
            // rule applies inside flow hooks (their receiver is FlowCollector).
            adapterField != null && thisQualifier != null ->
                CodeBlock.of("%L?.let { this@%L.%L.render(it) }", value, thisQualifier, adapterField)
            adapterField != null -> CodeBlock.of("%L?.let { this.%L.render(it) }", value, adapterField)
            // Top-level extension wrappers have no type body to host fields;
            // adapters are instantiated inline instead.
            meta.adapterFqn != null -> CodeBlock.of("%L?.let { %T().render(it) }", value, ClassName.bestGuess(meta.adapterFqn))
            // Flow hooks capture `this` as the FlowCollector: extractor fields
            // must be reached through the qualified wrapper reference. The
            // validated() view contains throws and non-loggable output.
            extractorField != null && thisQualifier != null ->
                CodeBlock.of("%L?.let { this@%L.%L.validated().extract(it) }", value, thisQualifier, extractorField)
            extractorField != null ->
                CodeBlock.of("%L?.let { this.%L.validated().extract(it) }", value, extractorField)
            // Top-level wrappers have no type body to host fields: resolve the
            // extractor through the logger's registry at the call site.
            meta.extractorFqn != null -> {
                val type = ClassName.bestGuess(meta.extractorFqn)
                val resolution = if (meta.extractorInjected) {
                    CodeBlock.of("%L.extractors.require(%T::class)", locals.logger, type)
                } else {
                    val fallback = if (meta.extractorIsObject) CodeBlock.of("%T", type) else CodeBlock.of("%T()", type)
                    CodeBlock.of("%L.extractors.get(%T::class) { %L }", locals.logger, type, fallback)
                }
                CodeBlock.of("%L?.let { %L.validated().extract(it) }", value, resolution)
            }
            else -> value
        }
    }

    private enum class RenderPurpose { ID, ACTOR_ID, PLAIN, MASK, HASH }

    private fun changedComparison(
        change: ResolvedChange,
        op: ResolvedOp,
        locals: LocalNames,
    ): CodeBlock {
        val terminal = terminalType(change.before, op)
        return if (terminal != null && Ks.isArrayType(terminal)) {
            CodeBlock.of("!(%L contentEquals %L)", locals.changeBefore, locals.changeAfter)
        } else {
            CodeBlock.of("%L != %L", locals.changeBefore, locals.changeAfter)
        }
    }

    private fun terminalType(expr: ResolvedExpr, op: ResolvedOp): KSType? {
        val info = when (expr) {
            is ResolvedExpr.Param -> expr.chainInfo
            is ResolvedExpr.Result -> expr.chainInfo
            else -> null
        }
        info?.properties?.lastOrNull()?.let { return it.type.resolve() }
        return when (expr) {
            is ResolvedExpr.Param -> op.parameters.getOrNull(expr.index)?.type
            is ResolvedExpr.Result -> Ks.unwrapResult(op.returnType).first
            else -> null
        }
    }

    /**
     * Renders a compile-time-validated value expression to generated Kotlin.
     * Safe-call navigation (`?.`) is used uniformly so nullable chains never
     * require casts in generated code.
     */
    private fun renderValue(
        expr: ResolvedExpr,
        op: ResolvedOp,
        purpose: RenderPurpose,
        extractorFields: Map<String, String>,
        locals: LocalNames,
    ): CodeBlock = when (expr) {
        is ResolvedExpr.Constant -> when (purpose) {
            RenderPurpose.MASK -> CodeBlock.of("%T.MASK", MASKING_TYPE)
            RenderPurpose.HASH -> CodeBlock.of("%T.hash(%S)", MASKING_TYPE, expr.text)
            else -> CodeBlock.of("%S", expr.text)
        }

        is ResolvedExpr.ContextOf -> when (purpose) {
            RenderPurpose.MASK -> CodeBlock.of("%T.MASK", MASKING_TYPE)
            RenderPurpose.HASH ->
                CodeBlock.of("%T.hash(%L.attributes[%S])", MASKING_TYPE, locals.ctx, expr.key)
            else -> CodeBlock.of("%L.attributes[%S]", locals.ctx, expr.key)
        }

        is ResolvedExpr.ActorOf -> when (purpose) {
            RenderPurpose.MASK -> CodeBlock.of("%T.MASK", MASKING_TYPE)
            RenderPurpose.HASH -> CodeBlock.of("%T.hash(%L)", MASKING_TYPE, actorAccess(expr, locals))
            else -> actorAccess(expr, locals)
        }

        is ResolvedExpr.Param -> renderChain(
            base = CodeBlock.of("%L", op.parameters[expr.index].name),
            info = expr.chainInfo,
            purpose = purpose,
        )

        is ResolvedExpr.Result -> renderChain(
            base = if (expr.chainInfo?.resultUnwrapped == true) {
                CodeBlock.of("%L.getOrNull()", locals.result)
            } else {
                CodeBlock.of("%L", locals.result)
            },
            info = expr.chainInfo,
            purpose = purpose,
        )

        is ResolvedExpr.None -> throw IllegalStateException("internal: None is not a renderable value")
    }

    private fun actorAccess(expr: ResolvedExpr.ActorOf, locals: LocalNames): CodeBlock = when (expr.access) {
        null, "id" -> CodeBlock.of("%L.actor?.id", locals.ctx)
        "name" -> CodeBlock.of("%L.actor?.name", locals.ctx)
        "type" -> CodeBlock.of("%L.actor?.type?.name", locals.ctx)
        else -> CodeBlock.of("%L.actor?.attributes[%S]", locals.ctx, expr.access)
    }

    private fun renderChain(base: CodeBlock, info: ChainInfo?, purpose: RenderPurpose): CodeBlock {
        val chainInfo = info
            ?: throw IllegalStateException("internal: chain expression was not validated before codegen")
        var access: CodeBlock = base
        for (property in chainInfo.properties) {
            access = CodeBlock.of("%L?.%L", access, property.simpleName.asString())
        }
        if (chainInfo.properties.isEmpty()) return when (purpose) {
            RenderPurpose.ID, RenderPurpose.ACTOR_ID -> CodeBlock.of("%L?.toString()", access)
            RenderPurpose.MASK -> CodeBlock.of("%T.MASK", MASKING_TYPE)
            RenderPurpose.HASH -> CodeBlock.of("%T.hash(%L)", MASKING_TYPE, access)
            RenderPurpose.PLAIN -> access
        }
        val terminal = chainInfo.properties.last().type.resolve()
        return when (purpose) {
            RenderPurpose.MASK -> CodeBlock.of("%T.MASK", MASKING_TYPE)
            RenderPurpose.HASH -> CodeBlock.of("%T.hash(%L)", MASKING_TYPE, access)
            RenderPurpose.ID, RenderPurpose.ACTOR_ID ->
                if (terminal.isStringLike()) access else CodeBlock.of("%L?.toString()", access)
            RenderPurpose.PLAIN ->
                if (terminal.isEnumKt()) CodeBlock.of("%L?.name", access) else access
        }
    }

    private fun KSType.isStringLike(): Boolean =
        declaration.qualifiedName?.asString() == "kotlin.String"

    private fun KSType.isEnumKt(): Boolean {
        val declaration = declaration as? KSClassDeclaration ?: return false
        if (declaration.classKind == ClassKind.ENUM_CLASS) return true
        return declaration.superTypes.any { superType ->
            superType.resolve().declaration.qualifiedName?.asString() == "kotlin.Enum"
        }
    }
