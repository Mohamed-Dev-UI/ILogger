package example.room

import androidx.room.Room
import androidx.sqlite.driver.bundled.BundledSQLiteDriver
import io.ilogger.annotations.DispatchMode
import io.ilogger.core.Actor
import io.ilogger.core.ILogger
import io.ilogger.core.withActor
import io.ilogger.core.sink.ConsoleLogSink
import io.ilogger.room.RoomLogSink
import io.ilogger.room.withAuditCallback
import io.ilogger.serialization.JsonEventCodec
import example.room.logged  // generated by ilogger-ksp
import kotlinx.coroutines.CompletableDeferred
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.runBlocking
import java.io.File

/**
 * Same task flows as before — but now every event the logger emits is also
 * PERSISTED into this app's own Room table (`log_events`, see
 * [LogEntity]) via [RoomLogSink], next to the unchanged console output.
 *
 * Proof of persistence: after the logger closes (which drains the buffered
 * queue into Room), the demo queries the table back and prints it, then runs
 * a retention purge.
 */
fun main(): Unit = runBlocking {
    // The logger is built before the database (the db builder below registers
    // lifecycle hooks into it), yet the sink needs the DAO that only exists
    // after Room.build(). The readiness gate resolves the cycle deterministically:
    // lifecycle events enqueued during build() simply await the DAO in the
    // buffered worker instead of being dropped.
    val logDaoReady = CompletableDeferred<LogDao>()
    val logger = ILogger.create {
        sink(ConsoleLogSink())
        // The external LogEntity target: one batched @Insert per batch.
        sink(
            RoomLogSink { events ->
                val logDao = logDaoReady.await()
                logDao.insertAll(events.map { it.toLogRow(payloadJson = JsonEventCodec.encode(it)) })
            },
        )
        // DB writes must leave the hot path; close()/flush() drain the queue.
        dispatch = DispatchMode.BUFFERED
        batchSize = 8
    }

    val dbFile = File(System.getProperty("java.io.tmpdir"), "ilogger-room-example.db")
    dbFile.delete() // fresh demo state (onCreate instead of onOpen)
    val db = Room.databaseBuilder<AppDatabase>(name = dbFile.absolutePath)
        .setDriver(BundledSQLiteDriver())
        .setQueryCoroutineContext(Dispatchers.IO)
        .withAuditCallback(logger, label = dbFile.name)
        .build()

    val logDao = db.logDao()
    logDaoReady.complete(logDao) // unblock lifecycle events queued by build()

    logger.use {
        daoOperations(db, logger)
        logger.record(action = "app.stopped", source = "example.room.main")
    }
    // use{} has closed the logger — BUFFERED drained everything into Room.

    // Proof: read the external log table back.
    val stored = logDao.recent(limit = 8)
    println()
    println("=== log_events (most recent ${stored.size} rows) ===")
    stored.forEach { row ->
        println("  ${row.ts} [${row.level}] ${row.action} actor=${row.actorId ?: "none"}")
        println("      event=${row.eventId} json=${row.payloadJson.take(96)}")
    }

    // Retention demo: drop rows older than 30 days (usually nothing yet).
    val purged = logDao.purgeBefore(cutoff = System.currentTimeMillis() - 30L * 86_400_000)
    println("=== retention purge removed $purged row(s) older than 30 days ===")

    db.close()
}

private suspend fun daoOperations(db: AppDatabase, logger: ILogger) {
    // `.logged(logger)` — the generated wrapper around the Room DAO.
    val dao = db.taskDao().logged(logger)

    withActor(Actor.user("u-42", name = "Grace")) {
        val id = dao.insert(TaskRow(title = "audit everything"))
        dao.byId(id)
        dao.complete(id)
        dao.delete(id)
    }
}
