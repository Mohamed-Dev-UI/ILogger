package example.server

import example.server.logged  // generated by ilogger-ksp
import io.ilogger.annotations.DispatchMode
import io.ilogger.core.Actor
import io.ilogger.core.ILogger
import io.ilogger.core.sink.ConsoleLogSink
import io.ilogger.ktor.HttpAudit
import io.ilogger.ktor.withAuditContext
import io.ktor.server.application.install
import io.ktor.server.cio.CIO
import io.ktor.server.engine.embeddedServer
import io.ktor.server.request.receiveText
import io.ktor.server.response.respondText
import io.ktor.server.routing.get
import io.ktor.server.routing.post
import io.ktor.server.routing.routing
import java.net.URI
import java.net.http.HttpClient
import java.net.http.HttpRequest
import java.net.http.HttpResponse
import kotlinx.coroutines.runBlocking

fun main(): Unit = runBlocking {
    val logger = ILogger.create {
        sink(ConsoleLogSink())
        dispatch = DispatchMode.INLINE
    }
    logger.use {
        val repository = InMemoryOrderRepository().logged(logger)

        val engine = embeddedServer(CIO, host = "127.0.0.1", port = 0) {
            // Request/response audit on the same logger used by domain calls.
            install(HttpAudit)

            routing {
                // Default-excluded path: produces NO http.request events.
                get("/health") {
                    call.respondText("ok")
                }

                post("/orders") {
                    val title = call.receiveText()
                    call.withAuditContext(
                        actor = call.request.headers["X-User-Id"]?.let { Actor.user(it) },
                        "tenant" to "toronto",
                    ) {
                        repository.create(title)          // audit event: order.created
                        call.respondText("order created")
                    }
                }

                post("/orders/{id}/cancel") {
                    val id = call.parameters["id"]?.toLongOrNull()
                        ?: throw IllegalArgumentException("order id required")
                    call.withAuditContext(
                        actor = call.request.headers["X-User-Id"]?.let { Actor.user(it) },
                    ) {
                        repository.cancel(id)             // audit event: order.cancelled
                        call.respondText("cancelled")
                    }
                }

                // Throws inside the LogContext: CallFailed hook picks it up,
                // failure events carry the structured payload, never swallow.
                get("/orders/boom") {
                    call.withAuditContext {
                        throw IllegalStateException("payment gateway offline")
                    }
                }
            }
        }

        engine.start(wait = false)
        val port = engine.engine.resolvedConnectors().first().port
        val base = "http://127.0.0.1:$port"
        val client = HttpClient.newHttpClient()

        suspend fun http(method: String, path: String, body: String? = null, headers: Map<String, String> = emptyMap()): HttpResponse<String> {
            val builder = HttpRequest.newBuilder(URI.create(base + path))
            for ((name, value) in headers) builder.header(name, value)
            when (method) {
                "GET" -> builder.GET()
                "POST" -> builder.POST(HttpRequest.BodyPublishers.ofString(body ?: ""))
                else -> error("unsupported method $method")
            }
            return client.send(builder.build(), HttpResponse.BodyHandlers.ofString())
        }

        println("--- GET /health  (excluded: no events expected)")

        println("--- POST /orders (no client correlation id → server generates)")
        val created = http("POST", "/orders", "double espresso", mapOf("X-User-Id" to "u-9"))
        println("    status=${created.statusCode()} echoed-correlation=${created.headers().firstValue("X-Request-Id").orElse("-")}")

        println("--- POST /orders (client-supplied correlation id)")
        val created2 = http(
            "POST", "/orders", "flat white",
            mapOf("X-Request-Id" to "client-req-42", "X-User-Id" to "u-9"),
        )
        println("    status=${created2.statusCode()}")

        println("--- POST /orders/1/cancel")
        val cancelled = http("POST", "/orders/1/cancel", null, mapOf("X-User-Id" to "u-9"))
        println("    status=${cancelled.statusCode()}")

        println("--- GET /orders/boom (500 → CallFailed hook, failure payload)")
        val boom = http("GET", "/orders/boom", null, mapOf("X-User-Id" to "u-9"))
        println("    status=${boom.statusCode()}")

        println("--- GET /missing (404 → failure via ResponseSent)")
        val missing = http("GET", "/missing")
        println("    status=${missing.statusCode()}")

        engine.stop(gracePeriodMillis = 500, timeoutMillis = 1000)
    }
    println("--- server example done")
}
